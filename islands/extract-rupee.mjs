// Extracts the ₹ (U+20B9) outline from an open-licensed font installed via @fontsource and
// writes it as plain path commands, so the site ships one shape, not a whole font.
//   node extract-rupee.mjs <family> <weight> [out]   e.g. node extract-rupee.mjs noto-sans 800
import fs from 'node:fs';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const opentype = require('opentype.js');
const [family = 'noto-sans', weight = '800', out = 'rupeeGlyph.js'] = process.argv.slice(2);
const dir = `node_modules/@fontsource/${family}/files`;

for (const file of fs.readdirSync(dir).filter((f) => f.endsWith(`-${weight}-normal.woff`))) {
  const font = opentype.parse(fs.readFileSync(`${dir}/${file}`).buffer.slice(0));
  const glyph = font.charToGlyph('₹');
  if (!glyph || glyph.index === 0 || !glyph.path.commands.length) continue;

  // Font units, y pointing up (as fonts store it). Rounded to keep the file small.
  const r = (v) => Math.round(v * 10) / 10;
  const commands = glyph.path.commands.map((c) => {
    const o = { t: c.type };
    for (const k of ['x1', 'y1', 'x2', 'y2', 'x', 'y']) if (k in c) o[k] = r(c[k]);
    return o;
  });
  fs.writeFileSync(
    out,
    `// ₹ outline from ${font.names.fullName?.en || family} (SIL Open Font License 1.1).\n` +
      `// Generated by extract-rupee.mjs from ${file}. Font units, y up. M/L/Q/C/Z commands.\n` +
      `export const RUPEE_GLYPH = ${JSON.stringify(commands)};\n`
  );
  console.log(`₹ from ${file}: ${commands.length} commands -> ${out}`);
  process.exit(0);
}
console.error(`No ₹ glyph in @fontsource/${family} weight ${weight}`);
process.exit(1);
